"""Render docs/tools.md from the registry, so the document cannot drift from the code.

python -m exchange_mcp.docs > docs/tools.md
"""

from __future__ import annotations

import asyncio

from exchange_mcp.registry import AREAS


async def render() -> str:
    from exchange_mcp.budget import measure
    from exchange_mcp.registry import all_tools

    m = await measure(frozenset(AREAS))
    specs = all_tools()
    out = ["# Tools", "", "Generated by `python -m exchange_mcp.docs` from the registry; CI fails when it differs.", ""]
    for area, default_on in AREAS.items():
        tools = sorted((s for s in specs.values() if s.area == area), key=lambda s: s.name)
        if not tools:
            continue
        out += [f"## {area}" + ("" if default_on else " (off by default)"), ""]
        for s in tools:
            flags = [
                f
                for f, on in (
                    ("read-only", s.read_only),
                    ("notifies others", s.notifies_others),
                    ("irreversible", s.irreversible),
                    ("idempotent", s.idempotent),
                )
                if on
            ]
            out += [
                f"### `{s.name}`: {s.title}",
                "",
                f"{', '.join(flags) or 'writes'} · {m['tools'].get(s.name, 0)} tokens",
                "",
                s.description,
                "",
            ]
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    print(asyncio.run(render()), end="")
